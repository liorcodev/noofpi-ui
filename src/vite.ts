const DTS = `// Generated by noofpi-ui
export {};

declare module "vue" {
  export interface GlobalComponents {
${COMPONENTS.map((name) => `    ${name}: typeof import("noofpi-ui")["${name}"];`).join("\n")}
  }
}
`;

// Compiled templates reference components as `_resolveComponent("NButton")` (or `n-button`)
const RESOLVE = /_?resolveComponent\d*\("([^"]+)"\)/g;

const toPascal = (name: string) =>
  name.replace(/(^|-)([a-z0-9])/g, (_, __, char: string) => char.toUpperCase());

/**
 * Vite plugin for noofpi (`vite: { plugins: [noofpiUi()] }` in `noofpi.config.ts`):
 * - auto-imports the `N*` components in templates, like noofpi does for `app/components`
 * - bundles noofpi-ui for SSR (it ships `.vue` source)
 * - writes their types to `.noofpi/ui-components.d.ts`
 *
 * It does its own transform on purpose: noofpi's components plugin marks every SFC it processed as done,
 * so a second instance of it would never see them.
 */
export function noofpiUi(): Plugin {
  return {
    name: "noofpi-ui",
    enforce: "post",
    config: () => ({
      ssr: { noExternal: ["noofpi-ui"] },
      optimizeDeps: { exclude: ["noofpi-ui"] },
    }),
    configResolved(config) {
      const file = path.join(config.root, ".noofpi/ui-components.d.ts");
      if (existsSync(file) && readFileSync(file, "utf8") === DTS) return;
      mkdirSync(path.dirname(file), { recursive: true });
      writeFileSync(file, DTS);
    },
    transform(code, id) {
      if (!/\.vue(\?|$)/.test(id) || /[\\/]node_modules[\\/]/.test(id)) return;
      if (!code.includes("resolveComponent")) return;

      const s = new MagicString(code);
      const imported = new Map<string, string>();
      for (const match of code.matchAll(RESOLVE)) {
        const name = toPascal(match[1]!);
        if (!COMPONENTS.includes(name)) continue;
        let local = imported.get(name);
        if (!local) {
          local = `__noofpi_ui_${name}`;
          imported.set(name, local);
        }
        s.overwrite(match.index, match.index + match[0].length, local);
      }
      if (!imported.size) return;

      s.prepend(
        [...imported]
          .map(
            ([name, local]) =>
              `import { ${name} as ${local} } from "noofpi-ui";\n`,
          )
          .join(""),
      );
      return { code: s.toString(), map: s.generateMap({ hires: "boundary" }) };
    },
  };
}
